using System;
using System.IO;
using System.Linq;
using RaidPrototype;
using RaidPrototype.Content;

internal static class Program
{
    private static int assertions;
    private static void Check(bool condition, string message)
    {
        assertions++;
        if (!condition) throw new Exception("FAIL: " + message);
    }
    private static void Reject(string json, string message)
    {
        int before = ContentRegistry.Packs.Count;
        bool rejected = false;
        try { ContentLoader.RegisterJson(json); } catch (ArgumentException) { rejected = true; }
        Check(rejected, message);
        Check(ContentRegistry.Packs.Count == before, message + " (no registration side effect)");
    }
    private static void RejectBudget(string json, string expectedMessage)
    {
        int packs = ContentRegistry.Packs.Count;
        string message = null;
        try { ContentLoader.RegisterJson(json); } catch (ArgumentException error) { message = error.Message; }
        Check(message != null && message.Contains(expectedMessage, StringComparison.Ordinal), "reject exact budget: " + expectedMessage);
        Check(ContentRegistry.Packs.Count == packs, "budget rejection is atomic: " + expectedMessage);
    }
    private static void RejectAtStage(string json, string expectedMessage, bool parserException)
    {
        int packs = ContentRegistry.Packs.Count;
        ArgumentException error = null;
        try { ContentLoader.RegisterJson(json); } catch (ArgumentException ex) { error = ex; }
        Check(error != null && error.Message.Contains(expectedMessage, StringComparison.Ordinal), "stage-specific failure: " + expectedMessage);
        Check((error.InnerException is Newtonsoft.Json.JsonException) == parserException, "real parser exception distinguishes lexical / parse / DTO budget stages");
        Check(ContentRegistry.Packs.Count == packs, "stage rejection is atomic");
    }
    private static string BudgetPack(string tail) => "{\"apiVersion\":1,\"id\":\"test.budget\",\"nameZh\":\"测试\",\"nameEn\":\"Budget\",\"skins\":[{\"id\":\"test.budget.default\",\"nameZh\":\"测试\",\"nameEn\":\"Budget\"}]," + tail + "}";
    private static string Repeat(string value, int count) => string.Join(",", Enumerable.Repeat(value, count));
    private static string OriginalParseCsvValue(string value)
    {
        value = value.Trim();
        if (value.StartsWith("\"", StringComparison.Ordinal) && value.EndsWith("\"", StringComparison.Ordinal))
            value = value.Substring(1, value.Length - 2).Replace("\"\"", "\"");
        return value.Replace("\\n", "\n");
    }
    private static void ValidateGeneratedCsv()
    {
        // This fixture is freshly generated by the real PowerShell generator at build time.
        string[] rows = File.ReadAllLines(Path.Combine(AppContext.BaseDirectory, "generated-content.csv"));
        Check(rows.Length == 1, "actual generator emits a single CSV row");
        int comma = rows[0].IndexOf(',');
        Check(comma > 0 && rows[0].Substring(0, comma) == "raid_framework_pack_v1", "CSV first-comma key matches original localization loader");
        string restored = OriginalParseCsvValue(rows[0].Substring(comma + 1));
        string id = ContentLoader.RegisterJsonForProvider(restored, "example.raiddocks");
        var pack = ContentRegistry.Packs.Single(p => p.Id == id);
        Check(pack.Maps.Length == 1 && pack.Weapons.Length == 1 && pack.Items.Length == 2 && pack.Skins.Length == 1,
            "generated CSV -> original ParseCsvValue -> real RegisterJson preserves 1 map / 1 weapon / 2 items / 1 skin");
        var map = pack.Maps[0];
        Check(map.Id == "example.raiddocks.warehouse" && map.NameZh == "夜港仓库 24×16", "CSV keeps night harbor identity and Unicode");
        Check(map.Width == 24 && map.Height == 16 && map.PlayerSpawn.X == 2 && map.ExtractionPoint.X == 22 && map.ExtractionSeconds == 4,
            "CSV preserves night harbor schema coordinates and extraction");
        Check(map.Enemies.Length == 3 && map.Boxes.Length == 3 && map.Obstacles.Length == 3 && map.Boxes[1].Loot.Length == 2,
            "CSV preserves all nested night harbor arrays");
        var model = new RaidModel(map.Id);
        Check(model.MapBounds.MaxX == 24 && model.MapBounds.MaxY == 16 && model.Enemies.Count == 3 && model.Boxes.Count == 3,
            "model really uses night harbor schema rather than built-in map");
        Check(model.CurrentWeapon.Id == "example.raiddocks.carbine" && model.CurrentWeapon.Damage == 24 && model.Skin.Floor.R == .06f,
            "model resolves night harbor loadout and palette");
        Check(model.Fire(new Vec2(10, 2)), "CSV-created night harbor model can fire");
        ContentRegistry.Unregister(id);
    }
    public static void Main()
    {
        string json = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "pack.json"));
        Console.WriteLine("Parser assembly: " + typeof(Newtonsoft.Json.Linq.JObject).Assembly.Location);
        string managed = Environment.GetEnvironmentVariable("GameManaged");
        if (string.IsNullOrWhiteSpace(managed)) managed = Environment.GetEnvironmentVariable("PROBABLY_STOLEN_MANAGED");
        string root = Environment.GetEnvironmentVariable("GameRoot");
        if (string.IsNullOrWhiteSpace(root)) root = Environment.GetEnvironmentVariable("PROBABLY_STOLEN_ROOT");
        if (string.IsNullOrWhiteSpace(managed) && !string.IsNullOrWhiteSpace(root))
            managed = Path.Combine(root, "Probably Stolen_Data", "Managed");
        if (string.IsNullOrWhiteSpace(managed))
            throw new InvalidOperationException("Set GameManaged or PROBABLY_STOLEN_MANAGED (or PROBABLY_STOLEN_ROOT) for the original Newtonsoft byte comparison. A build-only -p:GameManaged property is not a runtime environment variable.");
        byte[] expectedDll = File.ReadAllBytes(Path.Combine(managed, "Newtonsoft.Json.dll"));
        Check(expectedDll.SequenceEqual(File.ReadAllBytes(typeof(Newtonsoft.Json.Linq.JObject).Assembly.Location)),
            "tests execute byte-identical game Managed/Newtonsoft.Json.dll (not managed parser substitute)");
        Reject(null, "null JSON"); Reject("  ", "blank JSON"); Reject("[]", "array root");
        Reject("{broken}", "malformed JSON");
        Reject("null", "null root");
        Reject("{} {}", "multiple roots");
        Reject("{\"apiVersion\":1,\"apiVersion\":1}", "duplicate root key");
        Reject(json.Replace("\"damage\": 24", "\"damage\":24,\"damage\":24"), "duplicate nested key");
        Reject(json.Replace("\"requires\": []", "\"requires\": [], \"future\": {\"x\":1,\"x\":2}"), "duplicate unknown key");
        Reject("{\"apiVersion\":1,\"id\":\"test.empty\",\"nameZh\":\"空包\",\"nameEn\":\"Empty\"}", "empty pack cannot report success");
        Reject(json.Replace("\"maps\": [", "\"Maps\": [").Replace("\"items\": [", "\"Items\": [").Replace("\"weapons\": [", "\"Weapons\": [").Replace("\"skins\": [", "\"Skins\": ["), "all wrong-case arrays cannot silently succeed as empty pack");
        Reject(json.Replace("\"width\": 2,", "\"width\": 2.0,"), "integer DTO fields reject float tokens");
        Reject(json.Replace("\"width\": 2,", "\"width\": \"2\","), "integer DTO fields reject string coercion");
        Reject(json.Replace("\"width\": 2,", "\"width\": 2147483648,"), "integer overflow");
        Reject(json.Replace("\"width\": 2,", "\"width\": null,"), "integer null is not a number");
        Reject(json.Replace("\"damage\": 24", "\"damage\": \"24\""), "number fields reject string coercion");
        Reject(json.Replace("\"damage\": 24", "\"damage\": null"), "number fields reject null");
        Reject(json.Replace("\"damage\": 24", "\"damage\": NaN"), "registry rejects non-finite NaN");
        Reject(json.Replace("\"damage\": 24", "\"damage\": Infinity"), "registry rejects non-finite infinity");
        Reject(json.Replace("\"automatic\": true", "\"automatic\": \"true\""), "boolean rejects string coercion");
        Reject(json.Replace("\"automatic\": true", "\"automatic\": 1"), "boolean rejects number coercion");
        Reject(json.Replace("\"width\": 24", "\"Width\": 24"), "nested field names are case sensitive and missing number defaults to zero");
        Reject(json.Replace("\"maps\": [", "\"maps\": {\"ignored\": [").Replace("\n  ]\n}", "\n  ]}\n}"), "known maps field must be an array");
        string providerFailure = null;
        try { ContentLoader.RegisterJsonForProvider(json, "EXAMPLE.raiddocks"); } catch (ArgumentException ex) { providerFailure = ex.Message; }
        Check(providerFailure != null && providerFailure.Contains("provider manifest ID", StringComparison.Ordinal), "provider id matching is ordinal");
        Check(ContentRegistry.Packs.Count == 0, "provider id mismatch is atomic");
        RejectBudget(new string(' ', ContentLoader.MaxJsonCharacters + 1), "MaxJsonCharacters");
        RejectBudget(BudgetPack("\"unknown\":" + new string('[', 32) + "0" + new string(']', 32)), "MaxJsonDepth");
        RejectBudget(BudgetPack("\"items\":[" + Repeat("{}", ContentRegistry.MaxDefinitionsPerPack + 1) + "]"), "items (max");
        RejectBudget(BudgetPack("\"maps\":[" + Repeat("{}", 129) + "]"), "maps (max");
        RejectBudget(BudgetPack("\"requires\":[" + Repeat("\"p\"", ContentRegistry.MaxPacks + 1) + "]"), "requires (max");
        RejectBudget(BudgetPack("\"maps\":[{\"enemies\":[" + Repeat("{}", ContentRegistry.MaxEnemiesPerMap + 1) + "]}]"), "map.enemies (max");
        RejectBudget(BudgetPack("\"maps\":[{\"boxes\":[" + Repeat("{}", ContentRegistry.MaxBoxesPerMap + 1) + "]}]"), "map.boxes (max");
        RejectBudget(BudgetPack("\"maps\":[{\"obstacles\":[" + Repeat("{}", ContentRegistry.MaxObstaclesPerMap + 1) + "]}]"), "map.obstacles (max");
        RejectBudget(BudgetPack("\"maps\":[{\"loadout\":[" + Repeat("\"w\"", 65) + "]}]"), "map.loadout (max");
        RejectBudget(BudgetPack("\"maps\":[{\"boxes\":[{\"loot\":[" + Repeat("{}", ContentRegistry.MaxLootEntriesPerBox + 1) + "]}]}]"), "box.loot (max");
        string fullBoxes = Repeat("{\"loot\":[" + Repeat("{}", ContentRegistry.MaxLootEntriesPerBox) + "]}", ContentRegistry.MaxBoxesPerMap);
        int budgetMaps = ContentLoader.MaxNestedNodes / (ContentRegistry.MaxBoxesPerMap * (1 + ContentRegistry.MaxLootEntriesPerBox)) + 1;
        string hugeTree = BudgetPack("\"maps\":[" + Repeat("{\"boxes\":[" + fullBoxes + "]}", budgetMaps) + "]");
        Check(hugeTree.Length < ContentLoader.MaxJsonCharacters && budgetMaps <= 128, "aggregate budget fixture stays within lexical/per-array limits");
        RejectBudget(hugeTree, "MaxNestedNodes");
        RejectAtStage("{broken}" + new string(' ', ContentLoader.MaxJsonCharacters), "MaxJsonCharacters", false);
        RejectAtStage("{broken," + new string('[', 33), "MaxJsonDepth", false);
        RejectAtStage("{broken}", "Invalid content JSON", true);
        RejectAtStage(BudgetPack("\"items\":[" + Repeat("{}", ContentRegistry.MaxDefinitionsPerPack + 1) + "]"), "items (max", false);
        string boundary = BudgetPack("\"unknown\":" + new string('[', 31) + "0" + new string(']', 31));
        string boundaryId = ContentLoader.RegisterJson(boundary);
        Check(boundaryId == "test.budget", "depth 32 including root is accepted");
        ContentRegistry.Unregister(boundaryId);
        string escapedValue = new string('[', 50) + "\\\"quoted\\\"\\\\suffix" + new string('}', 50);
        boundaryId = ContentLoader.RegisterJson(BudgetPack("\"unknown\":\"" + escapedValue + "\""));
        Check(boundaryId == "test.budget", "braces, escaped quotes and escaped backslashes inside strings do not count as nesting");
        ContentRegistry.Unregister(boundaryId);
        string maxSize = BudgetPack("\"unknown\":0");
        maxSize += new string(' ', ContentLoader.MaxJsonCharacters - maxSize.Length);
        boundaryId = ContentLoader.RegisterJson(maxSize);
        Check(boundaryId == "test.budget", "exact character limit is accepted before trim");
        ContentRegistry.Unregister(boundaryId);
        Reject(json.Replace("\"apiVersion\": 1,", ""), "version is mandatory");
        Reject(json.Replace("\"apiVersion\": 1", "\"apiVersion\": 0"), "version zero");
        Reject(json.Replace("\"apiVersion\": 1", "\"apiVersion\": 2"), "version two");
        Reject(json.Replace("\"apiVersion\": 1", "\"ApiVersion\": 1"), "keys are case sensitive");
        Reject(json.Replace("\"damage\": 24", "\"damage\": -1"), "negative weapon damage");
        Reject(json.Replace("\"requires\": []", "\"requires\": [\"missing.pack\"]"), "missing content dependency");
        Reject(json.Replace("\"skinId\": \"example.raiddocks.night\"", "\"skinId\": \"missing.skin\""), "missing skin reference");
        Reject(json.Replace("\"items\": [", "\"items\": [null,"), "null definition");
        Reject(json.Replace("\"playerSpawn\": { \"x\": 2, \"y\": 2 }", "\"playerSpawn\": null"), "missing spawn");
        Check(ContentRegistry.Packs.Count == 0, "loader failures do not even auto-register built-in content");

        DefaultContent.EnsureRegistered();
        Check(ContentRegistry.Weapons.Count == 2, "two built-in weapons before third-party example");
        string id = ContentLoader.RegisterJson(json);
        Check(id == "example.raiddocks", "return registered pack id");
        Check(ContentRegistry.Packs.Count == 2 && ContentRegistry.Weapons.Count == 3, "standalone pack adds third weapon");
        Check(ContentRegistry.Items.Count == 3 && ContentRegistry.Maps.Count == 2 && ContentRegistry.Skins.Count == 2, "adds two items, another map, another skin");
        var map = ContentRegistry.GetMap("example.raiddocks.warehouse");
        Check(map.Width == 24 && map.Height == 16, "24x16 map is not the hardcoded demo");
        Check(map.Obstacles.Length == 3 && map.Obstacles[0].MinX == 7 && map.Obstacles[0].MaxY == 11, "writable rect DTO became readonly Rect");
        Check(map.Boxes[1].Loot.Length == 2 && map.Boxes[1].Loot[0].ItemId == "example.raiddocks.medical", "nested loot conversion");
        Check(ContentRegistry.GetSkin(map.SkinId).WallKey == "example.raiddocks:dock_wall", "third-party sprite prefix survives conversion");
        var session = new RaidModel(map.Id);
        Check(session.CurrentWeapon.Id == "example.raiddocks.carbine" && session.CurrentWeapon.Automatic, "new gun playable in model loadout");
        Check(session.Fire(new Vec2(10, 2)), "new gun can actually fire");
        Reject(json, "duplicate register");
        ContentRegistry.Unregister(id);
        Check(session.MapBounds.MaxX == 24 && session.Enemies.Count == 3, "running session survives registry unload");
        Check(session.CurrentWeapon.Damage == 24 && session.Skin.UIText.A == 1, "snapshot keeps weapon and skin after unload");
        session.Reset();
        Check(session.Boxes.Count == 3 && session.CurrentWeapon.Id == "example.raiddocks.carbine", "reset uses snapshot after unload");

        id = ContentLoader.RegisterJson(json.Replace("\"apiVersion\": 1,", "\"apiVersion\": 1, \"unknownFutureField\": 987,"));
        Check(ContentRegistry.IsRegistered(id), "unknown fields deliberately ignored");
        ContentRegistry.Unregister(id);
        id = ContentLoader.RegisterJson("{\"apiVersion\":1,\"id\":\"test.skin\",\"nameZh\":\"测试\",\"nameEn\":\"Test\",\"skins\":[{\"id\":\"test.skin.default\",\"nameZh\":\"颜色\",\"nameEn\":\"Colors\"}]}");
        var skin = ContentRegistry.GetSkin("test.skin.default");
        Check(skin.Floor.A == 1 && skin.Player.A == 1 && skin.Enemy.A == 1 && skin.UIText.A == 1 && skin.UIBackground.A == 1, "omitted skin colors are opaque safe defaults");
        Check(skin.Floor.R > 0 && skin.UIText.R > .5f, "default skin is not all zeros");
        ContentRegistry.Unregister(id);

        id = ContentLoader.RegisterJson(json.Replace("\"nameEn\": \"Third-party example: Night Docks\"", "\"nameEn\": \"2026-11-02T01:35:35Z\"")
            .Replace("\"apiVersion\": 1,", "\"apiVersion\": 1, \"$type\":\"Unknown.Never.Resolve, Missing.Assembly\", \"future\":{\"$type\":\"System.IO.FileInfo\"},"));
        Check(ContentRegistry.Packs.Single(p => p.Id == id).NameEn == "2026-11-02T01:35:35Z", "ISO-looking JSON strings are not coerced to Date tokens");
        Check(ContentRegistry.GetMap("example.raiddocks.warehouse").Enemies.Length == 3, "$type is an ignored unknown field, never type metadata");
        ContentRegistry.Unregister(id);
        Reject(json.Replace("\"apiVersion\": 1", "\"apiVersion\": 1.0"), "apiVersion must use an integer token");
        Reject(json.Replace("\"apiVersion\": 1", "\"apiVersion\": \"1\""), "apiVersion string is not accepted");
        Reject(json.Replace("\"damage\": 24", "\"damage\": 1e100"), "float overflow is rejected by registry finite check");
        id = ContentLoader.RegisterJson(json.Replace("\"speed\": 1.6,", "\"Speed\": 1.6,"));
        Check(ContentRegistry.GetMap("example.raiddocks.warehouse").Enemies[0].Speed == 0, "wrong-case optional numeric field is ignored and missing value remains zero");
        ContentRegistry.Unregister(id);
        ValidateGeneratedCsv();
        Check(ContentRegistry.IsRegistered(DefaultContent.PackId), "loader tests leave the framework built-in pack registered");
        Console.WriteLine("PASS: " + assertions + " JSON loader/model assertions (real game Newtonsoft.Json.dll, generated CSV + original parse rules; no Entry or live ModLoader bridge test).");
    }
}
